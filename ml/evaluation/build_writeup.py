#!/usr/bin/env python3
"""Drafts the Devpost evaluation text and the honesty statement from the real result files (never typed from memory).
    python ml/evaluation/build_writeup.py     ->  docs/devpost-draft.md
Anything not measured yet is printed as [NOT YET MEASURED: ...]. Edit the wording, never the numbers: rerun the script instead."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from build_evaluation import ROOT, load, pc  # noqa: E402

NM = lambda what: f"[NOT YET MEASURED: {what}]"
L = ["# Devpost draft (generated by `ml/evaluation/build_writeup.py`)", "",
     "## What is simulated and what is real (honesty statement)", "",
     "**Simulated in the sandbox:** the company (150 employees), its asset register, SaaS subscriptions, seat-usage logs and 90-day purchase history, "
     "and the vendors (two vendor agents we wrote, each with its own PayPal sandbox merchant account).",
     "**Real:** benchmark prices come from the real Channel3 catalog (five anchor products). Mandates, verification, orders, subscriptions, the ledger and the dashboard are real code against real PayPal sandbox APIs. [CONFIRM WITH BAI/SWE before keeping this sentence: executePurchase must create and capture real sandbox orders, not just generate a reference.]",
     "**AI components:** an LLM (`deepseek-chat`) compiles plain-English policies; the planning agent is deterministic, and a deterministic verifier decides whether money moves. [CONFIRM: model name actually deployed.]",
     "**Measured on synthetic data:** every ML and backtest number below. They are upper bounds, not field results. The policy and abuse test suites were written by the team and are published in the repo.", ""]
pol = load("ml/policy_eval/results/test_metrics.json")
L += ["## Policy compiler", ""]
if pol:
    m = pol["metrics"]["TEST"]
    L.append(f"On a held-out set of {m['n_clear'] + m['n_hard']} hand-written policies (run once, prompt frozen), the compiler produced the exactly correct policy for {pc(m['clear_exact_rate'])} of {m['n_clear']} clear inputs "
             f"and guessed on {pc(m['guess_rate'])} of {m['n_hard']} ambiguous or adversarial inputs (it asks a question instead). Schema validity {pc(m['schema_valid_rate'])}.")
else:
    L.append(NM("policy compiler test split"))
L += ["", "## Break-it Arena", ""]
ar, fz = load("arena/results/summary.json"), load("arena/results/fuzz.json")
if ar:
    L.append(f"{ar['safety_pass']} of the {ar['attacks_run']} attacks we could drive at the deterministic verifier were stopped safely, with false-block rate {ar['control_false_block_rate']} on legitimate purchases. "
             f"{len(ar['skipped'])} further cases are not yet runnable and are not counted. Our first run found fail-open gaps in the verifier; they were fixed (see `arena/findings/FINDINGS.md`).")
else:
    L.append(NM("Arena pass rate"))
if fz:
    L.append(f"A randomized fuzzer ran {fz['n']:,} verifications plus {fz['hash_checks']} hash checks and reported {len(fz['violations'])} kind(s) of violation in the final version.")
L += ["", "## Benchmark coverage", ""]
pr = load("ml/channel3_probe/out/summary.json")
L.append(f"Of {pr['n_queries']} business-hardware queries against Channel3, {pr['usable']} returned a usable benchmark (at least 3 priced, in-stock offers). Docking stations were reliable; laptops were the weakest category, so the demo anchors on five specific products." if pr else NM("Channel3 coverage"))
L += ["", "## Savings projection and ML (synthetic)", ""]
bt = load("seed/backtest-demo.json")
if bt:
    s, d = bt["backtest"]["summary"], bt["backtest"]["savings_decomposition"]
    c = s["counts"]
    L.append(f"Replaying 90 days of synthetic purchasing under the demo policy: {c['auto_approved']} auto-approved, {c['escalated']} escalated for human approval, {c['blocked']} blocked by the circuit breaker. "
             f"Realized savings (auto-approved only) ${s['realized_savings']:,.2f}, of which ${d['realized_list_price_only']:,.2f} comes from choosing the cheaper vendor and the rest from negotiation. The top three purchases account for {pc(s['top3_share_of_positive_savings'])} of positive savings.")
else:
    L.append(NM("backtest"))
L += ["", "Full tables: `docs/evaluation.md`. Limitations: the generator makes cleanly separable behaviour, planted anomalies are 30% of the history, and savings depend on our simulated vendors.", ""]
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "devpost-draft.md").write_text("\n".join(L))
print("wrote docs/devpost-draft.md;", sum(x.startswith("[NOT YET") for x in L), "section(s) still not measured")
