#!/usr/bin/env python3
"""Writes docs/demo-numbers.md: for every anchored SKU, what each vendor quotes, what the agent would pay, and the verdict under
the demo policy. Vendor-kit (task A6) must reproduce the 'list' and 'after counters' columns; the demo script can quote the verdicts.

    python apps/ml/demo_numbers.py
"""
import json
from pathlib import Path

from core import backtest as B
from run_backtest import DEMO_POLICY

ROOT = Path(__file__).resolve().parents[2]
catalog = json.loads((ROOT / "seed" / "catalog.json").read_text())
vendors = json.loads((ROOT / "seed" / "vendors.json").read_text())
SENTENCE = "Laptops and monitors, up to $1,800 each, $12,000 a month, vendors A and B only, no more than 10% over market, buy automatically."

rows, L = [], []
for c in catalog:
    sku, cat, m = c["sku"], c["category"], c["market_price"]
    quotes = {}
    for v, cfg in vendors.items():
        if sku in cfg["skus"]:
            quotes[v] = [B.negotiate(cfg, cat, m, r) for r in range(0, cfg["max_rounds"] + 1)]
    probe = {"id": sku, "ordered_at": "2026-10-05T10:00:00Z", "vendor_id": "vendor_a", "sku": sku, "category": cat, "quantity": 1,
             "unit_price": round(m * 1.10, 2), "benchmark_price": m, "currency": "USD"}
    p = B.replay(DEMO_POLICY, [probe], vendors=vendors, details=True)["purchases"][0]
    rows.append((c, quotes, p))

L += ["# Demo numbers (generated by `apps/ml/demo_numbers.py`; do not edit by hand)", "",
      "Prices are anchored to real Channel3 medians (`ml/seedgen/anchors.json`). Vendors are simulated around them.", "",
      f"**Demo policy sentence:** {SENTENCE}", "",
      "Compiles to: " + json.dumps(DEMO_POLICY) + ". Because the sentence uses `$`, the compiler adds a currency warning (USD assumed); write `USD` to avoid it.", "",
      "Quantity 1, fresh month. The buyer counters at the benchmark; each vendor concedes a fixed share of the gap per round, never below its floor.", "",
      "| SKU | product | market | vendor_a list / after 3 rounds | vendor_b list / after 3 rounds | agent buys | verdict | why |", "|---|---|---|---|---|---|---|---|"]
for c, q, p in rows:
    f = lambda v: f"${q[v][0]:,.2f} / ${q[v][-1]:,.2f}" if v in q else "not stocked"
    L.append(f"| {c['sku']} | {c['name'][:42]} | ${c['market_price']:,.2f} | {f('vendor_a')} | {f('vendor_b')} | {p['agent_vendor']} @ ${p['agent_unit_price']:,.2f} | {p['verdict']} | {', '.join(p['reasons']) or 'all checks pass'} |")
L += ["", "## Round by round (what a vendor's `/counter` must return, buyer countering at the market price)", "",
      "| SKU | vendor | round 0 (list) | round 1 | round 2 | round 3 |", "|---|---|---|---|---|---|"]
for c, q, _ in rows:
    for v, seq in q.items():
        L.append(f"| {c['sku']} | {v} | " + " | ".join(f"${x:,.2f}" for x in seq) + " |")
L += ["", "## Reading this", "",
      "- Anything the verdict column marks `escalated` is a natural 'manager signs the Cart Mandate' moment for the demo.",
      "- If vendor-kit quotes differ from the round-by-round table, either the vendors or `seed/vendors.json` is wrong. Fix the vendors, not this file.", ""]
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "demo-numbers.md").write_text("\n".join(L))
print("\n".join(L[8:20]))
